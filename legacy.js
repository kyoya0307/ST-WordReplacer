// 原作者 OwO 的上下文规则，独立开关；启发式匹配仍可能误判。
export function legacyBefore(text) {
  const insultPattern = /[丑臭傻蠢烂恶疯泼贱肥破脏坏龟老死]+\s*(娘们|三八|八婆|婆娘|马子)/giu;
  text = text.replace(insultPattern, '');

  return text;
}
export function legacyAfter(text) {
  // 3. 处理带“去”的特殊句型 (双重锁定)
  // a. 如果后面跟着白名单名词（狗屁不在里面），则只把“妈”拿掉。例如：“去他妈的狗屁” -> “去他的狗屁”
  text = text.replace(/去(你|他|她|它|牠|祂|[tT][aA])(妈的|娘的)(?!(?:东西|家|房|车|钱|包|事|朋友|同学|老师|手机|衣服|鞋|书|笔|饭|菜|照片|工作|单位|公司|病|生日|名字|项链|戒指|眼镜|钥匙|电脑|猫|狗|手艺))/g, '去$1的');
  // b. 处理没带“的”的情况，如果后面跟着亲属词，则受保护不替换。
  text = text.replace(/去(你|他|她|它|牠|祂|[tT][aA])(妈|娘)(?!的|\s*[妈咪亲祖舅家那这])/g, '去$1');

  // ================= 核心防御网 (最终版) =================
  
  // 4. “操”相关连招阻断及智能替换
  text = text.replace(/(我?操)\s*(?:你|他|她|它|牠|祂|[tT][aA])?(?:妈|娘)的?/g, match => match.startsWith('我') ? '我劁' : '劁');
  text = text.replace(/(?<![\u4e00-\u9fa5])我操(?![\u4e00-\u9fa5])/gu, '我劁');
  text = text.replace(/(?<![\u4e00-\u9fa5])操(?![\u4e00-\u9fa5])/gu, '劁');

  // 5. 核心清道夫：动词 + 名词 双重护盾！
  // 只要前面不是动作护盾，且后面不是名词护盾，通通作为脏话秒杀！
  // 这完美保护了：“这是他妈的家”、“别碰他妈的东西”、“我想他妈的手艺了”
  text = text.replace(/(?<![是想看听找回像接送陪帮爱疼恨打问求叫认给跟同带摸抱亲夸骂碰拿买偷抢去])(你|他|她|它|牠|祂|[tT][aA])(妈的|娘的)(?!(?:东西|家|房|车|钱|包|事|朋友|同学|老师|手机|衣服|鞋|书|笔|饭|菜|照片|工作|单位|公司|病|生日|名字|项链|戒指|眼镜|钥匙|电脑|猫|狗|手艺))/g, '');

  // 6. 前缀绑定脏话（修饰语连击，防误伤“你娘真好”、“这妈的”）
  // a. 主语连击：“你他妈” -> “你”
  text = text.replace(/(谁|大家|你|我|他|她|它|你们|我们|他们)(他|她|它|牠|祂|你|我|[tT][aA])(妈|娘)的?(?!\s*[妈咪亲祖舅家])/g, '$1');
  // b. 副词连击：“真妈的” / “真他娘” -> “真”
  text = text.replace(/(真|太|最|简直|特么|还|又|竟|竟然|老子|别)(?:他|她|它|牠|祂|你|我|[tT][aA])?(妈|娘)的?(?!\s*[妈咪亲祖舅家])/g, '$1');
  // c. 语气词连击：“这他娘” -> “这”
  text = text.replace(/(这|那|都|就|全)(他|她|它|牠|祂|你|我|[tT][aA])(妈|娘)的?(?!\s*[妈咪亲祖舅家])/g, '$1');
  // d. 处理“全是/都是/就是/总是 + 他妈的”
text = text.replace(/(全|都|就|总)是(他|她|它|牠|祂|你|我|[tT][aA])(妈|娘)的?(?!\s*[妈咪亲祖舅家])/g, '$1是');
  // 7. 处理纯粹落单的语气词（两边都没汉字才删）
  text = text.replace(/(?<![\u4e00-\u9fa5])(妈的|娘的)(?![\u4e00-\u9fa5])/g, '');

  // ==========================================================

  // 8. “三八”相关智能替换
  text = text.replace(/(?<![零一二两三四五六七八九十百千万亿0-9])三八(?!妇女节|节|线|红|大盖|[零一二两三四五六七八九十百千万亿0-9])/g, '');

  return text;
}
